import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from google.colab import files
import io

# ---------------------------------------------------------
# 1. Cargar el CSV
# ---------------------------------------------------------
subido = files.upload()                      # te abre un botón para elegir el CSV
nombre = list(subido.keys())[0]
df = pd.read_csv(io.BytesIO(subido[nombre])) # si separa con ; agrega sep=";"

# Columnas de pacientes = las que empiezan con GSM
gsm_cols = [c for c in df.columns if c.startswith("GSM")]
print(f"{len(gsm_cols)} pacientes, {df.shape[0]} reacciones")

# ---------------------------------------------------------
# 2. Matriz pacientes x reacciones
# ---------------------------------------------------------
# En tu CSV las filas son reacciones y las columnas pacientes,
# pero para agrupar pacientes necesitamos lo contrario (transponer)
X = df[gsm_cols].apply(pd.to_numeric, errors="coerce")
X.index = df.iloc[:, 0]            # primera columna = ID de la reacción
X = X.T                            # filas = pacientes, columnas = reacciones

# Limpieza: Imputar valores faltantes con 0 (en lugar de eliminar con dropna)
# para no perder todas las columnas si todas tienen algún NaN
X = X.fillna(0)

# Quitar reacciones que no varían (desviación estándar igual a 0, no aportan nada)
X = X.loc[:, X.std() > 0]

# ---------------------------------------------------------
# 3. Estandarizar (para que ninguna reacción domine por escala)
# ---------------------------------------------------------
X_scaled = StandardScaler().fit_transform(X)

# ---------------------------------------------------------
# 4. Elegir el número de grupos (k) con silhouette
#    (mientras más cerca de 1, mejor separados están los grupos)
# ---------------------------------------------------------
mejor_k, mejor_score = 2, -1
for k in range(2, min(8, len(X) - 1)):
    labels = KMeans(n_clusters=k, n_init=10, random_state=42).fit_predict(X_scaled)
    score = silhouette_score(X_scaled, labels)
    print(f"k={k}  silhouette={score:.3f}")
    if score > mejor_score:
        mejor_k, mejor_score = k, score

print(f"\nMejor k: {mejor_k}")

# ---------------------------------------------------------
# 5. Clustering final
# ---------------------------------------------------------
km = KMeans(n_clusters=mejor_k, n_init=10, random_state=42)
grupos = pd.Series(km.fit_predict(X_scaled), index=X.index, name="grupo")

grupos.to_csv("pacientes_por_grupo.csv")
print(grupos.sort_values())

# ---------------------------------------------------------
# 6. Visualización 1: PCA (mapa 2D de los pacientes)
# ---------------------------------------------------------
pca = PCA(n_components=2)
coords = pca.fit_transform(X_scaled)

plt.figure(figsize=(7, 6))
sns.scatterplot(x=coords[:, 0], y=coords[:, 1], hue=grupos.values,
                palette="tab10", s=100)
for i, nombre_paciente in enumerate(X.index):
    plt.annotate(nombre_paciente, (coords[i, 0], coords[i, 1]), fontsize=7)
plt.xlabel(f"PC1 ({pca.explained_variance_ratio_[0]*100:.1f}%)")
plt.ylabel(f"PC2 ({pca.explained_variance_ratio_[1]*100:.1f}%)")
plt.title("Pacientes agrupados por perfil metabólico")
plt.tight_layout()
plt.savefig("pca_pacientes.png", dpi=300)
plt.show()

# ---------------------------------------------------------
# 7. Visualización 2: heatmap con dendrograma
# ---------------------------------------------------------
colores = dict(zip(sorted(grupos.unique()), sns.color_palette("tab10", mejor_k)))
fila_colores = grupos.map(colores)

sns.clustermap(pd.DataFrame(X_scaled, index=X.index, columns=X.columns),
               method="ward", cmap="vlag", center=0,
               row_colors=fila_colores, xticklabels=False,
               figsize=(12, 8))
plt.savefig("heatmap_pacientes.png", dpi=300)
plt.show()

# ---------------------------------------------------------
# 8. ¿Qué reacciones/subsistemas distinguen a los grupos?
# ---------------------------------------------------------
X_df = pd.DataFrame(X_scaled, index=X.index, columns=X.columns)
medias = X_df.groupby(grupos).mean().T          # reacción x grupo
medias["diferencia"] = medias.max(axis=1) - medias.min(axis=1)

# Unir con nombre de reacción y subsistema
info = df.iloc[:, [0, 1, 2]].copy()
info.columns = ["reaccion", "nombre_reaccion", "subsistema"]
top = (medias.sort_values("diferencia", ascending=False)
             .head(30)
             .reset_index()
             .rename(columns={medias.index.name or "index": "reaccion"}))
top = top.merge(info, on="reaccion", how="left")
top.to_csv("reacciones_que_separan_grupos.csv", index=False)
print(top[["reaccion", "nombre_reaccion", "subsistema", "diferencia"]])