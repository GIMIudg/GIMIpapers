import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import glob, os, re, zipfile
from google.colab import files
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

# ---------------------------------------------------------
# CONFIGURACIÓN: cambia esto según tus archivos
# ---------------------------------------------------------
SON_CONTEOS_CRUDOS = True   # True si son lecturas (counts enteros)
                            # False si ya vienen normalizados (TPM, FPKM, etc.)

# ---------------------------------------------------------
# 1. Subir el zip y descomprimir
# ---------------------------------------------------------
subido = files.upload()                       # sube tu .zip con los txt
nombre_zip = list(subido.keys())[0]
with zipfile.ZipFile(nombre_zip) as z:
    z.extractall("datos")

rutas = [r for r in glob.glob("datos/**/*", recursive=True)
         if os.path.isfile(r) and os.path.basename(r).upper().startswith("GSM")]
print(f"{len(rutas)} archivos de pacientes encontrados")

# ---------------------------------------------------------
# 2. Leer cada archivo: gen + expresión
# ---------------------------------------------------------
def leer_paciente(ruta):
    # sep=None: detecta solo si separa con tab, coma, espacio, etc.
    df = pd.read_csv(ruta, sep=None, engine="python", header=None, usecols=[0, 1])
    # Si la primera fila es encabezado (texto en la columna de valores), se quita
    if pd.isna(pd.to_numeric(df.iloc[0, 1], errors="coerce")):
        df = df.iloc[1:]
    serie = pd.Series(pd.to_numeric(df[1], errors="coerce").values,
                      index=df[0].astype(str).values)
    return serie.groupby(level=0).sum()       # si un gen se repite, se suman

columnas = {}
for ruta in sorted(rutas):
    gsm = re.search(r"GSM\d+", os.path.basename(ruta), re.I).group(0).upper()
    columnas[gsm] = leer_paciente(ruta)

expr = pd.DataFrame(columnas).fillna(0)       # genes x pacientes
print(expr.shape, "(genes x pacientes)")
print(expr.head())

# ---------------------------------------------------------
# 3. Normalizar
# ---------------------------------------------------------
if SON_CONTEOS_CRUDOS:
    cpm = expr / expr.sum(axis=0) * 1e6                  # corrige profundidad
    mantener = (cpm > 1).sum(axis=1) >= 0.2 * expr.shape[1]  # quita genes sin expresión
    logexpr = np.log2(cpm[mantener] + 1)
else:
    logexpr = np.log2(expr + 1)
    logexpr = logexpr[(logexpr > 0).sum(axis=1) >= 0.2 * expr.shape[1]]

# Los 2000 genes más variables (los que realmente distinguen pacientes)
top_var = logexpr.var(axis=1).nlargest(2000).index
X = logexpr.loc[top_var].T                   # filas = pacientes, columnas = genes
X = X.loc[:, X.std() > 0]

# ---------------------------------------------------------
# 4. Estandarizar
# ---------------------------------------------------------
X_scaled = StandardScaler().fit_transform(X)

# ---------------------------------------------------------
# 5. Elegir k con silhouette
# ---------------------------------------------------------
mejor_k, mejor_score = 2, -1
for k in range(2, min(8, len(X) - 1)):
    labels = KMeans(n_clusters=k, n_init=10, random_state=42).fit_predict(X_scaled)
    score = silhouette_score(X_scaled, labels)
    print(f"k={k}  silhouette={score:.3f}")
    if score > mejor_score:
        mejor_k, mejor_score = k, score
print(f"\nMejor k: {mejor_k}")

# ---------------------------------------------------------
# 6. Clustering final
# ---------------------------------------------------------
km = KMeans(n_clusters=mejor_k, n_init=10, random_state=42)
grupos = pd.Series(km.fit_predict(X_scaled), index=X.index, name="grupo")
grupos.to_csv("pacientes_por_grupo.csv")
print(grupos.sort_values())

# ---------------------------------------------------------
# 7. PCA
# ---------------------------------------------------------
pca = PCA(n_components=2)
coords = pca.fit_transform(X_scaled)

plt.figure(figsize=(7, 6))
sns.scatterplot(x=coords[:, 0], y=coords[:, 1], hue=grupos.values,
                palette="tab10", s=100)
for i, nombre_paciente in enumerate(X.index):
    plt.annotate(nombre_paciente, (coords[i, 0], coords[i, 1]), fontsize=6)
plt.xlabel(f"PC1 ({pca.explained_variance_ratio_[0]*100:.1f}%)")
plt.ylabel(f"PC2 ({pca.explained_variance_ratio_[1]*100:.1f}%)")
plt.title("Pacientes agrupados por expresión génica")
plt.tight_layout()
plt.savefig("pca_pacientes.png", dpi=300)
plt.show()

# ---------------------------------------------------------
# 8. Heatmap con dendrograma
# ---------------------------------------------------------
colores = dict(zip(sorted(grupos.unique()), sns.color_palette("tab10", mejor_k)))
sns.clustermap(pd.DataFrame(X_scaled, index=X.index, columns=X.columns),
               method="ward", cmap="vlag", center=0,
               row_colors=grupos.map(colores),
               xticklabels=False, yticklabels=False, figsize=(12, 8))
plt.savefig("heatmap_pacientes.png", dpi=300)
plt.show()

# ---------------------------------------------------------
# 9. Genes que más separan los grupos
# ---------------------------------------------------------
X_df = pd.DataFrame(X_scaled, index=X.index, columns=X.columns)
medias = X_df.groupby(grupos).mean().T
medias["diferencia"] = medias.max(axis=1) - medias.min(axis=1)
top = medias.sort_values("diferencia", ascending=False).head(30)
top.to_csv("genes_que_separan_grupos.csv")
print(top)

# Descargar resultados
for f in ["pacientes_por_grupo.csv", "pca_pacientes.png",
          "heatmap_pacientes.png", "genes_que_separan_grupos.csv"]:
    files.download(f)